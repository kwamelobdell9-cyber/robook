drop policy if exists "users create own likes" on public.post_likes;
create policy "users create own likes" on public.post_likes for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "users delete own likes" on public.post_likes;
create policy "users delete own likes" on public.post_likes for delete to authenticated using ((select auth.uid()) = user_id);

-- Comments
 drop policy if exists "comments readable by signed in users" on public.comments;
create policy "comments readable by signed in users" on public.comments for select to authenticated using (true);
drop policy if exists "users create own comments" on public.comments;
create policy "users create own comments" on public.comments for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "users delete own comments" on public.comments;
create policy "users delete own comments" on public.comments for delete to authenticated using ((select auth.uid()) = user_id);

-- Direct messages: only the sender or recipient can see/send/delete their own conversation messages.
drop policy if exists "messages readable by participants" on public.messages;
create policy "messages readable by participants" on public.messages for select to authenticated using ((select auth.uid()) = sender_id or (select auth.uid()) = recipient_id);
drop policy if exists "users send own messages" on public.messages;
create policy "users send own messages" on public.messages for insert to authenticated with check ((select auth.uid()) = sender_id and sender_id <> recipient_id);
drop policy if exists "users delete own messages" on public.messages;
create policy "users delete own messages" on public.messages for delete to authenticated using ((select auth.uid()) = sender_id);

