insert into storage.buckets (id, name, public) values ('roobook-images','roobook-images',true)
on conflict (id) do update set public = true;
drop policy if exists "roobook images readable" on storage.objects;
create policy "roobook images readable" on storage.objects for select to public using (bucket_id = 'roobook-images');
drop policy if exists "users upload roobook images" on storage.objects;
create policy "users upload roobook images" on storage.objects for insert to authenticated with check (bucket_id = 'roobook-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
drop policy if exists "users update roobook images" on storage.objects;
create policy "users update roobook images" on storage.objects for update to authenticated using (bucket_id = 'roobook-images' and owner_id = (select auth.uid())::text);
drop policy if exists "users delete roobook images" on storage.objects;
create policy "users delete roobook images" on storage.objects for delete to authenticated using (bucket_id = 'roobook-images' and owner_id = (select auth.uid())::text);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username, display_name, avatar)
  values (new.id, lower(regexp_replace(coalesce(new.raw_user_meta_data->>'username','user_'||substr(new.id::text,1,8)), '[^a-zA-Z0-9_]', '', 'g')), coalesce(new.raw_user_meta_data->>'display_name','Robook User'), upper(left(coalesce(new.raw_user_meta_data->>'display_name','R'),2)))
  on conflict (id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
